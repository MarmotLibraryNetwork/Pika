#!/usr/bin/env bash
# Refresh docker/db/sql/ from a development database, so new Docker databases start
# from the current schema. Run on the machine that hosts the database:
#
#   docker/db/dump-schema.sh [site]        (site defaults to $PIKA_SITE, then marmot.localhost)
#
# The connection details are read from sites/<site>/conf/config.pwd.ini. Only table
# structure and the db_update rows are dumped; no other data leaves the database.
set -euo pipefail

REPO="$(cd "$(dirname "$0")/../.." && pwd -P)"
SITE="${1:-${PIKA_SITE:-marmot.localhost}}"
PWD_INI="${REPO}/sites/${SITE}/conf/config.pwd.ini"
OUT="${REPO}/docker/db/sql"

[[ -f "$PWD_INI" ]] || { echo "Cannot find ${PWD_INI}" >&2; exit 1; }

# Keep the password off the command line: write a client option file that only we can read.
CNF="$(mktemp)"
trap 'rm -f "$CNF"' EXIT
chmod 600 "$CNF"
php -r '
	$config = parse_ini_file($argv[1], true, INI_SCANNER_RAW);
	$dsn    = parse_url(trim($config["Database"]["database_vufind"] ?? "", "\""));
	if (empty($dsn["user"])) { fwrite(STDERR, "No [Database] database_vufind in $argv[1]\n"); exit(1); }
	echo "[client]\nuser=\"{$dsn["user"]}\"\npassword=\"" . urldecode($dsn["pass"] ?? "") . "\"\nhost=" . ($dsn["host"] ?? "localhost") . "\n";
' "$PWD_INI" > "$CNF"

dump() {
	mariadb-dump --defaults-extra-file="$CNF" --single-transaction --skip-comments --skip-dump-date --no-tablespaces "$@"
}

header() {
	printf -- '-- %s\n-- Generated by docker/db/dump-schema.sh; do not edit by hand.\n-- Loaded by docker/db/10-pika-init.sh when the db container is first initialised.\n\n' "$1"
}

schema() {
	header "$1 database schema (no data)"
	dump --no-data --routines --triggers "$1" | sed -E 's/ AUTO_INCREMENT=[0-9]+//'
}

mkdir -p "$OUT"
schema pika     > "${OUT}/pika_schema.sql"
schema econtent > "${OUT}/econtent_schema.sql"
{
	header "pika.db_update rows: the DB Maintenance updates already contained in pika_schema.sql"
	dump --no-create-info --skip-extended-insert --order-by-primary pika db_update
} > "${OUT}/pika_db_update_data.sql"

echo "Wrote:"
grep -c '^CREATE TABLE' "${OUT}/pika_schema.sql" "${OUT}/econtent_schema.sql"
grep -c '^INSERT' "${OUT}/pika_db_update_data.sql" | sed "s|^|${OUT}/pika_db_update_data.sql (rows):|"
